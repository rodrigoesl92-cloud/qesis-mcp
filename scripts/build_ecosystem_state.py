def _strip_volatile(x):
    """Remove everything that legitimately differs between machines.

    `probe` results are host dependent by design: the Windows paths resolve on
    the operator's desktop, do not resolve on a GitHub runner, and do not resolve
    on the analysis mount. Comparing them would make --check fail on every
    machine that did not happen to generate the file, and the two would overwrite
    each other forever. That is a ping-pong, not a control. The DECLARED paths
    are compared; what a given filesystem can see of them is reported and not
    asserted as ecosystem state.

    The same argument covers ledger and ladder facts on a partial checkout, so
    those are compared only when both sides carry them.
    """
    # Everything MEASURED is stripped. This is the correction that matters.
    #
    # The first version compared the whole file, including ledger_facts and
    # ladder_facts. Those move whenever the ledger or the ladder moves, and the
    # lander regenerates the state BEFORE appending new lesson entries, so the
    # committed copy was stale the instant it was written. CI then failed on
    # every single run with "ECOSYSTEM_STATE.json disagrees with a fresh
    # measurement", which is a gate no correct action can satisfy: exactly the
    # deadlock SH-10f was written about, rebuilt one file later.
    #
    # What --check must actually guard is the STATIC CONTRACT a session reads at
    # start: where the repositories are, which lookalike paths are decoys, and
    # the hard constraints. Those do not move between runs. The measured block
    # stays IN the file, carries its own timestamp, and is informational.
    #
    # `repository` joined the set on 2026-08-24 evening (L-170). It is the NAME
    # OF THE CHECKOUT DIRECTORY, so it differs between the two repositories by
    # construction, and the same generated file is mirrored into both. Comparing
    # it made --check pass in qesis-mcp and fail in sovereign-infra on identical
    # bytes, which is the third occurrence of a gate no correct action could
    # satisfy: L-158, L-166, and this. The file still records it; it is a
    # measurement of where the file was generated, not a contract.
    # `rdl_pending_consumed` joined the set on 2026-08-28 with the same argument
    # that put `rdl_pending_append` here, and it is stated rather than assumed:
    # the two repositories hold DIFFERENT pending files by construction, because
    # the truncation that clears them survives in one checkout and not in the
    # other. Comparing it would make --check pass in qesis-mcp and fail in
    # sovereign-infra on a correct tree, which is L-158, L-166 and L-170 reached
    # a fourth time. It is measured, it stays IN the file, it is not a contract.
    VOLATILE = {
        "generated_utc", "probe", "repository",
        "ledger", "rdl_ladder", "served_vintage",
        "rdl_pending_append", "rdl_pending_consumed",
        "decision_documents_present",
        "promotion_policy_signed",
    }
    if isinstance(x, dict):
        return {k: _strip_volatile(v) for k, v in x.items() if k not in VOLATILE}
    if isinstance(x, list):
        return [_strip_volatile(v) for v in x]
    return x


def canon(d: dict) -> str:
    """Stable serialisation with volatile and host-dependent fields removed, so
    --check compares substance rather than the clock or the filesystem."""
    return json.dumps(_strip_volatile(json.loads(json.dumps(d))), sort_keys=True)


def check_files(fresh: dict) -> list[str]:
    """Compare committed copies against fresh measurements on the static contract only."""
    bad = []
    for path, doc in fresh.items():
        if not path.exists():
            bad.append(f"{path.name} is absent")
            continue
        try:
            have = json.loads(path.read_text(encoding="utf-8"))
        except Exception as exc:
            bad.append(f"{path.name} is unreadable: {exc}")
            continue
        if canon(have) != canon(doc):
            bad.append(f"{path.name} disagrees with a fresh measurement")
    return bad


def selftest() -> int:
    """V-2. The check must ACCEPT a copy that differs only in what legitimately
    moves between machines and runs, and must REFUSE a copy whose static
    contract moved. Both halves, or the gate is a coin."""
    import copy as _copy
    import tempfile
    fails: list[str] = []
    n = 0  # L-201: a sub-suite reports the count it MEASURED, never a literal.
    state, registry = build_state(), build_registry()
    with tempfile.TemporaryDirectory() as d:
        sp, rp = Path(d) / "ECOSYSTEM_STATE.json", Path(d) / "PATH_REGISTRY.json"

        # ACCEPT: volatile drift only. Another repository, another clock,
        # another filesystem, another ledger hash, another vintage.
        s2, r2 = _copy.deepcopy(state), _copy.deepcopy(registry)
        s2["repository"] = "some-other-checkout-name"
        s2["generated_utc"] = "1999-01-01T00:00:00Z"
        s2["ledger"] = {"entries": 0, "sha256": "0" * 64, "status": "FAIL"}
        s2["served_vintage"] = "v0.0"
        s2["rdl_pending_append"] = []
        r2["generated_utc"] = "1999-01-01T00:00:00Z"
        for entry in r2["canonical"].values():
            entry["probe"] = {"exists": True, "kind": "dir", "entries": 999}
        sp.write_text(json.dumps(s2), encoding="utf-8")
        rp.write_text(json.dumps(r2), encoding="utf-8")
        if check_files({sp: state, rp: registry}):
            fails.append("volatile-only drift was refused")
        n += 1

        # REFUSE: a canonical path moved.
        r3 = _copy.deepcopy(registry)
        r3["canonical"]["sovereign-infra"]["path"] = r"C:\Users\Lenovo\sovereign-infra"
        rp.write_text(json.dumps(r3), encoding="utf-8")
        if not check_files({rp: registry}):
            fails.append("a moved canonical path was accepted")
        n += 1

        # REFUSE: a hard constraint dropped.
        s3 = _copy.deepcopy(state)
        s3["hard_constraints"] = s3["hard_constraints"][:-1]
        sp.write_text(json.dumps(s3), encoding="utf-8")
        if not check_files({sp: state}):
            fails.append("a dropped hard constraint was accepted")
        n += 1

        # REFUSE: absent and unreadable.
        rp.unlink()
        if not check_files({rp: registry}):
            fails.append("an absent registry was accepted")
        n += 1
        sp.write_text("{not json", encoding="utf-8")
        if not check_files({sp: state}):
            fails.append("an unreadable state file was accepted")
        n += 1

    # ------------------------------------------------------------------
    # pending_facts, the 2026-08-28 repair. An id already in the ledger is
    # residue; an id that is not is outstanding work. Both halves, or the
    # split is a coin (V-2).
    # ------------------------------------------------------------------
    with tempfile.TemporaryDirectory() as d:
        ops = Path(d)
        (ops / "RDL_PENDING_APPEND.md").write_text(
            "**L-193 \u00b7 a lesson that has already been appended** body\n\n"
            "**L-902 \u00b7 a lesson that has not** body\n", encoding="utf-8")
        pend, cons = pending_facts(ops, {193})

        # REFUSE: the exact defect measured on 2026-08-28.
        if any("L-193" in e["ids"] for e in pend):
            fails.append("an id already in the ledger was reported as pending")
        n += 1
        # ACCEPT: a genuinely unappended id is still reported.
        if not any("L-902" in e["ids"] for e in pend):
            fails.append("a genuinely pending id was dropped")
        n += 1
        # The consumed half is declared, never silently erased (L-199).
        if not any("L-193" in e["ids"] for e in cons):
            fails.append("a consumed id was erased instead of declared")
        n += 1

        # A file whose every id is live yields zero pending and is not listed.
        (ops / "RDL_PENDING_APPEND.md").write_text(
            "**L-193 \u00b7 every id in this file is live** body\n", encoding="utf-8")
        pend2, cons2 = pending_facts(ops, {193})
        if pend2:
            fails.append("a fully consumed file was still reported as pending")
        n += 1
        if not cons2:
            fails.append("a fully consumed file was not declared as consumed")
        n += 1

        # An empty pending file is neither pending nor consumed. Zero is zero.
        (ops / "RDL_PENDING_APPEND.md").write_text("", encoding="utf-8")
        if pending_facts(ops, {193}) != ([], []):
            fails.append("an empty pending file produced a row")
        n += 1

    # V-6: the reader is on trial against the system's own accessor, not against
    # itself. If `_LEDGER_HEADER` ever diverges from the regex the two canonical
    # ledger writers use, this is where it is caught rather than in production.
    lf = ledger_facts()
    if lf.get("status") == "PASS":
        live = live_lesson_ids()
        if len(live) != lf.get("entries"):
            fails.append(f"live_lesson_ids read {len(live)} ids while "
                         f"verify_ledger_singleton reports {lf.get('entries')}")
        n += 1
        if lf.get("max") not in {f"L-{i:03d}" for i in live}:
            fails.append(f"live_lesson_ids does not carry the accessor's max, {lf.get('max')}")
        n += 1

    for f in fails:
        print(f"SELFTEST FAIL: {f}")
    print(f"ECOSYSTEM STATE SELFTEST: "
          + (f"PASSED, {n} fixtures" if not fails else f"FAILED, {len(fails)} of {n}"))
    return 1 if fails else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()

    if a.selftest:
        return selftest()

    fresh = {STATE: build_state(), REGISTRY: build_registry()}
    if a.check:
        bad = check_files(fresh)
        for b in bad:
            print(f"  STALE  {b}")
        print("ECOSYSTEM STATE CHECK " + ("FAILED" if bad else "PASSED"))
        if bad:
            print("  Regenerate with: python scripts/build_ecosystem_state.py")
        return 1 if bad else 0

    for path, doc in fresh.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}  "
              f"sha256 {hashlib.sha256(canon(doc).encode()).hexdigest()[:16]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
