#!/usr/bin/env python3
"""Generate the one file every session reads before it asserts anything.

WHY THIS EXISTS. Every serious failure of 2026-08-24 shares one shape: a session
made a claim about the ecosystem from something other than the ecosystem. A
connected folder that was empty became "the repository is unreachable" (L-143).
The tail of an unsorted file became "the next free id" (L-151). A parent count
became "this arrived through a pull request" (L-161). Parent count, folder
emptiness and file tails are all proxies, and D-115 rules that a control queries
the thing it asserts.

A session cannot query the ecosystem if it does not know where the ecosystem is.
So this writes two artefacts, both generated and never hand-edited:

    ops/PATH_REGISTRY.json    where everything actually is, and which lookalike
                              paths are decoys
    ops/ECOSYSTEM_STATE.json  what is true right now, measured

Both are regenerated by the self-heal loop and by CI, so a stale copy is a build
failure rather than a trap. `--check` exits non-zero when the committed copy
disagrees with a fresh measurement, exactly like build_graph and build_eval.

Usage:
    python scripts/build_ecosystem_state.py
    python scripts/build_ecosystem_state.py --check
    python scripts/build_ecosystem_state.py --selftest   # V-2 fixtures
"""
