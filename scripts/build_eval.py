"""Generate eval/evaluation.xml from the served index.

The v8.0 evaluation set was hand-written and went stale the moment the index was
corrected: it asserted Bahrain at composite 90.0 and a core coupling of 0.163,
both of which the rebuild changed. An eval set that disagrees with the system it
evaluates is worse than none, because it fails correct answers.

So it is generated. Every answer is read from the index at build time, and
--check re-derives the answers and fails if the committed file disagrees.

Usage:  python scripts/build_eval.py [--check]
"""
from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def pairs(doc: dict) -> list[tuple[str, str]]:
    C = doc["countries"]
    cp, model = doc["coupling"], doc["composite_model"]
    ranked = sorted(((i, c) for i, c in C.items() if c["composite"] is not None),
                    key=lambda t: -t[1]["composite"])
    top_iso, top = ranked[0]
    epis = doc.get("epis_findings", [])
    hi_ese = max(C.items(), key=lambda t: t[1]["axes"]["ESE"] or -1)
    hi_odi = max(C.items(), key=lambda t: t[1]["axes"]["ODI"] or -1)
    deu = C["DEU"]

    out = [
        ("Which country ranks first on composite exposure, and with what score?",
         f"{top['name']} ({top_iso}), {top['composite']:.1f}"),
        ("What is the substrate coupling ratio within the import-dependent core?",
         f"{cp['core']['CR']:.3f} at n={cp['core']['n']}"),
        ("What is the global substrate coupling ratio?",
         f"{cp['global']['CR']:.3f} at n={cp['global']['n']}"),
        ("Which country has the highest Electricity Stress Exposure (ESE) score?",
         f"{hi_ese[1]['name']} ({hi_ese[0]}), {hi_ese[1]['axes']['ESE']:.1f}"),
        ("Which country has the highest operator concentration (ODI)?",
         f"{hi_ese and hi_odi[1]['name']} ({hi_odi[0]}), {hi_odi[1]['axes']['ODI']:.1f}"),
        ("How is the composite exposure calculated?",
         f"{model['expression']}. Derived from the published axes at build time, "
         f"never carried."),
        ("Which states are not ranked, and why?",
         "; ".join(f"{C[e['iso3']]['name']} ({e['iso3']}) at coverage "
                   f"{e['coverage']:.2f}, missing "
                   f"{', '.join(e['missing_weighted_axes'])}" for e in epis)
         + f". Below the declared {model['big_coverage_min']} BIG coverage "
           f"threshold the composite is published as a gap, never imputed."),
        ("How many states are ranked and how many are published as gaps?",
         f"{len(ranked)} ranked, {len(epis)} published as gaps, "
         f"{len(C)} in the sample"),
        ("Which countries are excluded from the core sub-matrix?",
         "Six: " + ", ".join(cp["excluded_from_core"])),
        ("Which countries are excluded from the global coupling matrix, and why?",
         ", ".join(cp["excluded_from_global"]) + ". The global matrix requires a "
         "complete vector over the six coupling axes, so the omitted states are "
         "exactly those carrying a BIG coverage flag."),
        ("What is Germany's binding constraint and its composite?",
         f"{max((a for a in deu['axes'] if deu['axes'][a] is not None), key=lambda a: deu['axes'][a])}"
         f" at {max(v for v in deu['axes'].values() if v is not None):.1f}; "
         f"composite {deu['composite']:.1f}"),
        ("What weight does grid reliability carry in the ESE composite?",
         f"{doc['ese_method']['weights']['grid']} "
         f"({doc['ese_method']['weights']['grid']*100:.0f}%)"),
        ("How is the ODI axis constructed?",
         doc["odi_method"]["continuous"]),
        ("What is the necessity consistency of rare-earth dependence (REE)?",
         f"{doc['fsqca']['necessity']['REE']}, quasi-necessary"),
        ("Can fsQCA pathway memberships be cited from this vintage?",
         "No. The HYPER condition was calibrated on the ordinal ODI proxy and is "
         "flagged recalibration_required after ODI became continuous in v8.2."
         if doc["fsqca"].get("recalibration_required") else
         "Yes, the published solution is current."),
        ("Which vintage is being served and does it reproduce from its axes?",
         f"{doc['vintage']}, generated {doc['lineage']['generated_at_utc']}. "
         f"Every composite recomputes from the published axes; the gate fails "
         f"the deploy on drift."),
    ]
    return out


def render(doc: dict) -> str:
    body = "\n".join(
        f"  <qa_pair><question>{html.escape(q)}</question>"
        f"<answer>{html.escape(a)}</answer></qa_pair>"
        for q, a in pairs(doc))
    return (f"<evaluation vintage=\"{html.escape(doc['vintage'])}\" "
            f"generated=\"{html.escape(doc['lineage']['generated_at_utc'])}\">\n"
            f"  <!-- Generated by scripts/build_eval.py from data/qesis_v8.json.\n"
            f"       Do not hand-edit: a hand-written set went stale in v8.0 and\n"
            f"       began failing correct answers. -->\n{body}\n</evaluation>\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "eval" / "evaluation.xml"))
    ap.add_argument("--json", default=str(ROOT / "data" / "qesis_v8.json"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    doc = json.loads(Path(args.json).read_text(encoding="utf-8"))
    want = render(doc)
    out = Path(args.out)

    if args.check:
        have = out.read_text(encoding="utf-8") if out.exists() else ""
        if have.strip() != want.strip():
            print("eval set disagrees with the index; run scripts/build_eval.py",
                  file=sys.stderr)
            return 1
        print(f"eval set is in sync with {doc['vintage']} "
              f"({len(pairs(doc))} pairs).")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(want, encoding="utf-8")
    print(f"wrote {out} ({len(pairs(doc))} pairs) from {doc['vintage']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
